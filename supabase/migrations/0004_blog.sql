-- =============================================================================
-- 0004 — Blog: categories, posts (draft → published), image storage.
--
-- Run once in Supabase → SQL Editor (after 0001–0003). Safe to re-run.
--
-- Any admin can write, publish and edit posts. Editing a PUBLISHED post never
-- changes the live version directly: edits autosave into `pending`, and only
-- "Update post" copies them into the live columns (the site build reads the
-- live columns only). "Discard changes" just clears `pending`.
--
-- The public (anon key, used by the site build) reads published posts only.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Categories
-- -----------------------------------------------------------------------------
create table if not exists public.categories (
    id         smallint generated by default as identity primary key,
    slug       text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 60),
    name       text not null check (char_length(name) between 1 and 60),
    sort_order int not null default 0,
    created_at timestamptz not null default now()
);

